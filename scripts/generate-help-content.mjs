import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const content = path.join(root, "content/help");
const files = {};
for (const folder of readdirSync(content, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
  if (!folder.isDirectory()) continue;
  for (const file of readdirSync(path.join(content, folder.name)).sort()) {
    if (!file.endsWith(".md")) continue;
    files[`${folder.name}/${file}`] = readFileSync(path.join(content, folder.name, file), "utf8").replace(/\r\n/g, "\n");
  }
}
if (!Object.keys(files).length) throw new Error("No help articles found; refusing to build an empty help centre.");

// Pixel sizes of the screenshots, read from each PNG's IHDR chunk. A serverless
// deployment serves public/ from the CDN, so the page cannot read the files to
// size its figures; without this every figure falls back to a guessed ratio
// and the text jumps as it loads.
const imageSizes = {};
function walk(dir) {
  let entries = [];
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (entry.name.toLowerCase().endsWith(".png")) {
      const bytes = readFileSync(full);
      if (bytes.length >= 24 && bytes.toString("ascii", 12, 16) === "IHDR") {
        const src = "/" + path.relative(path.join(root, "public"), full).split(path.sep).join("/");
        imageSizes[src] = { width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20) };
      }
    }
  }
}
walk(path.join(root, "public/help/screenshots"));

writeFileSync(path.join(root, "src/lib/help/content.generated.ts"),
  `// Generated by scripts/generate-help-content.mjs. Edit content/help instead.\nconst content: Record<string, string> = ${JSON.stringify(files, null, 2)};\nexport default content;\n\n/** Pixel size of every PNG under public/help/screenshots, keyed by public path. */\nexport const imageSizes: Record<string, { width: number; height: number }> = ${JSON.stringify(imageSizes, null, 2)};\n`);
console.log(`Bundled ${Object.keys(files).length} help articles and ${Object.keys(imageSizes).length} screenshot sizes.`);
